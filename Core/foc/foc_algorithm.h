#ifndef __FOC_ALGORITHM_H
#define __FOC_ALGORITHM_H
#include "main.h"
#include "math.h"


#define PI 3.14159265358979f
#define Clw 0  //顺时针方向
#define Cow 1  //逆时针方向

/*********************************************************************************************************
*                                        FOC 数据流总览
*
*   输入(rtX)                中间量                          输出(rtY)
*
*   theta ──> Angle_To_Cos_Sin ──> Transf_Cos_Sin ──┐
*                                                    ├─> Rev_Park_Transf ──> Voltage_Alpha_Beta ──┐
*   Voltage_DQ (Vd/Vq 给定) ────────────────────────┘                                              ├─> SVPWM_Calc ──> Tcmp1/2/3
*   Udc, Tpwm ────────────────────────────────────────────────────────────────────────────────────┘
*
*   每个 PWM 周期调用一次 FOC_Run()，整个链条执行一遍，Tcmp 换算成 CCR 后写入定时器。
*********************************************************************************************************/

/*-------------------------------------------------------------------------------------------------------
* 输入结构体：每个控制周期开始前，由外部（ADC采样/编码器读取/上位机）填好，再调用 FOC_Run()
*------------------------------------------------------------------------------------------------------*/
typedef struct
{
    float theta;    // 转子电角度，单位 rad，范围 [0, 2PI)
                    // 来源：编码器/霍尔换算，或无感观测器输出
                    // 何时用：FOC_Run() 第一步 Angle_To_Cos_Sin() 计算 sin/cos，
                    //         供 Rev_Park_Transf() 做旋转坐标系 -> 静止坐标系变换
                    // 注意：必须是"电角度"= 机械角度 × 极对数，且要折算到 [0, 2PI)

    float Udc;      // 直流母线电压，单位 V
                    // 来源：ADC 采样母线分压电阻
                    // 何时用：SVPWM_Calc() 中做标幺化（Tpwm/Udc），把电压指令换算成矢量作用时间
                    // 注意：母线电压波动时实时更新可提高输出电压精度；必须防止为 0（除零）

    float Tpwm;     // PWM 周期，单位与定时器时基一致（如 us 或 s）
                    // 来源：由定时器配置决定（中心对齐模式 = 2×ARR×计数周期）
                    // 何时用：SVPWM_Calc() 中计算矢量作用时间 Tx/Ty、切换点 Ta/Tb/Tc
                    // 注意：rtY.Tcmp 与 Tpwm 同单位，写 CCR 前需换算 CCR = Tcmp × ARR / Tpwm
	
	uint8_t Dir;     //控制电机转动方向 
}ExtX;

/*-------------------------------------------------------------------------------------------------------
* 输出结构体：FOC_Run() 执行完毕后有效，三相桥臂的比较值，送入定时器 CCR1/2/3
*------------------------------------------------------------------------------------------------------*/
typedef struct
{
    float Tcmp1;    // U 相（A 相）桥臂比较值，时间量纲，范围 [0, Tpwm]
    float Tcmp2;    // V 相（B 相）桥臂比较值，时间量纲，范围 [0, Tpwm]
    float Tcmp3;    // W 相（C 相）桥臂比较值，时间量纲，范围 [0, Tpwm]
                    // 何时产生：SVPWM_Calc() 最后一步，按扇区把 Ta/Tb/Tc 分配给三相
                    // 何时使用：本周期 FOC_Run() 返回后，换算成计数值更新定时器 CCR
                    //           （中心对齐 PWM 通常在更新中断/下溢时装载，下个周期生效）
}ExtY;

/*-------------------------------------------------------------------------------------------------------
* 三角函数结构体：中间量，仅在 FOC_Run() 内部使用
*------------------------------------------------------------------------------------------------------*/
typedef struct
{
    float Cos;      // cos(theta)
    float Sin;      // sin(theta)
                    // 何时产生：FOC_Run() 第一步 Angle_To_Cos_Sin()，每个周期刷新一次
                    // 何时使用：Rev_Park_Transf() 的旋转矩阵元素
                    // 设计意图：theta 的 sin/cos 在同一个周期内会被 Park/反Park 多次用到，
                    //           只算一次存起来，避免重复调用 cosf/sinf 浪费算力
}Transf_Cos_Sin_DEF;

/*-------------------------------------------------------------------------------------------------------
* DQ 轴电压：旋转坐标系（随转子同步旋转）下的电压指令，FOC 的核心控制量
*------------------------------------------------------------------------------------------------------*/
typedef struct
{
    float Vd;       // d 轴电压，单位 V —— 励磁分量（对准转子磁场方向）
                    // 表贴式 PMSM 通常令 Vd 给定 = 0（id=0 控制，力矩/电流比最大）
                    // 内嵌式或弱磁工况才给负的 d 轴电流
    float Vq;       // q 轴电压，单位 V —— 转矩分量（与转速/出力直接相关）
                    // 何时产生：完整 FOC 中是电流环 PI 输出（id/iq 反馈 → PI → Vd/Vq）；
                    //           当前代码为开环验证阶段，由外部直接给定
                    // 何时使用：Rev_Park_Transf() 输入，旋转回静止坐标系
}Voltage_DQ_DEF;

/*-------------------------------------------------------------------------------------------------------
* Alpha-Beta 电压：静止两相坐标系电压，反 Park 变换的输出，SVPWM 的直接输入
*------------------------------------------------------------------------------------------------------*/
typedef struct
{
    float Valpha;   // alpha 轴电压，单位 V —— 与电机 U 相（A 相）轴线对齐
    float Vbeta;    // beta 轴电压，单位 V —— 滞后 alpha 轴 90° 电角度
                    // 何时产生：Rev_Park_Transf()，每个周期一次
                    // 何时使用：SVPWM_Calc() 用它判断扇区（N=4C+2B+A）并计算矢量作用时间
                    // 物理意义：Valpha + j*Vbeta 就是空间电压矢量 Vref，
                    //           SVPWM 的任务就是用两个相邻基本矢量 + 零矢量合成它
}Voltage_Alpha_Beta_DEF;

/*-------------------------------------------------------------------------------------------------------
* 三相电流结构体：当前代码未使用（保留给完整 FOC 电流环）
*------------------------------------------------------------------------------------------------------*/
typedef struct
{
    float Ia;       // U 相电流采样值，单位 A
    float Ib;       // V 相电流采样值，单位 A
    float Ic;       // W 相电流采样值，单位 A
                    // 将来用途：Clarke 变换（Ia/Ib/Ic -> Ialpha/Ibeta）
                    //           -> Park 变换（-> Id/Iq）-> 与给定比较 -> 电流环 PI -> Vd/Vq
                    // 工程提示：三电阻采样只需两相（Ia+Ib+Ic=0），单电阻采样需按扇区重构
}Current_ABC_DEF;

/*-------------------------------------------------------------------------------------------------------
* Alpha-Beta 电流结构体：Clarke 变换的输出
*------------------------------------------------------------------------------------------------------*/
typedef struct
{
    float Ialpha;
    float Ibeta;

}Current_Alpha_Beta_DEF;
/*-------------------------------------------------------------------------------------------------------
* Id-Iq 电流结构体：Park 变换的输出
*------------------------------------------------------------------------------------------------------*/
typedef struct
{
    float Id;
    float Iq;

}Current_Id_Iq_DEF;

// 全局变量声明
extern ExtX rtX;                              /* 输入：每周期外部填充 */
extern ExtY rtY;                              /* 输出：每周期算法刷新 */
extern Transf_Cos_Sin_DEF Transf_Cos_Sin;          /* 中间量：sin/cos */
extern Voltage_DQ_DEF Voltage_DQ;                  /* 给定：Vd/Vq 电压指令 */
extern Voltage_Alpha_Beta_DEF Voltage_Alpha_Beta;  /* 中间量：反Park输出 */

extern Current_ABC_DEF Current_Iabc;                 /*采样出的三相电流*/
extern Current_Alpha_Beta_DEF Current_Ialpha_beta;   /*中间量：Clarke变换输出*/
extern Current_Id_Iq_DEF Current_Id_Iq;              /*中间量：Park变换输出*/

// 函数声明
void FOC_Init(void);
void FOC_Run(void);
void Angle_To_Cos_Sin(float angle, Transf_Cos_Sin_DEF* cos_sin);
void Rev_Park_Transf(Voltage_DQ_DEF v_dq, Transf_Cos_Sin_DEF cos_sin, Voltage_Alpha_Beta_DEF* v_alpha_beta);
void SVPWM_Calc(Voltage_Alpha_Beta_DEF v_alpha_beta, float Udc, float Tpwm);

#endif
